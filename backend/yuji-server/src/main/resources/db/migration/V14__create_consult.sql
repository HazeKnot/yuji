CREATE TABLE consult_session (
    id         BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    topic_code VARCHAR(40)  NULL,
    title      VARCHAR(80)  NOT NULL,
    risk_level VARCHAR(10)  NOT NULL DEFAULT 'GREEN' COMMENT 'GREEN/YELLOW/RED',
    status     VARCHAR(20)  NOT NULL DEFAULT 'OPEN' COMMENT 'OPEN/REFERRED/CLOSED',
    created_at DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME     NULL,
    KEY idx_user (user_id, created_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '私密健康咨询会话';

CREATE TABLE consult_message (
    id         BIGINT AUTO_INCREMENT PRIMARY KEY,
    session_id BIGINT      NOT NULL,
    role       VARCHAR(20) NOT NULL COMMENT 'USER/ASSISTANT/SYSTEM',
    content    TEXT        NOT NULL,
    created_at DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_session (session_id, id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '咨询会话消息';
